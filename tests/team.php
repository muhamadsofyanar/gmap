<?php
// Behavioral tests against a real PDO database. SQLite is the fast local test driver.
require __DIR__ . '/bootstrap.php';
use App\Models\TeamRepository;
use App\Services\TeamAccess;

check(class_exists(TeamAccess::class), 'TeamAccess must exist before access can be enforced');
check(class_exists(TeamRepository::class), 'TeamRepository must exist');
$db = fixture();
$admin = ['id'=>1,'role'=>'admin','workspace_id'=>1];
$a = ['id'=>2,'role'=>'user','workspace_id'=>1];
$b = ['id'=>3,'role'=>'user','workspace_id'=>1];
$root = new TeamRepository($db,$admin);
$alice = new TeamRepository($db,$a);
$bob = new TeamRepository($db,$b);
foreach (['DashboardController','ProjectController','CrmController','ProspectController','ExtrasController','ReportsController','SalesController','SettingsController','IntakeController','TemplateController','RemindersController','LicenseController','AnythingController'] as $controller) {
    check(!TeamAccess::allowsController($a,$controller), 'member denied legacy '.$controller);
}
foreach (['TeamController','ProfileController','AuthController'] as $controller) check(TeamAccess::allowsController($a,$controller), 'member allowed '.$controller);
check(!TeamAccess::allowsController(['role'=>'owner'],$controller), 'unknown role denied');
check(TeamAccess::allowsController($admin,'ProjectController'), 'admin legacy works');
check(count($alice->listing())===1 && $alice->listing()[0]['id']==10,'member listing only own');
check($alice->listing('Bob')===[], 'foreign search empty');
check($alice->lead(11)===null && $alice->lead(12)===null && $root->lead(13)===null,'foreign/unassigned/workspace details denied');
check(count($root->listing())===3, 'admin sees all within workspace');
check((int)$alice->summary()['total']===1,'scoped report count');
check(count($alice->exportRows())===1, 'scoped export');
check($alice->attachment(21)===null && $alice->attachment(20)['name']==='a.pdf','scoped download');
check(count($alice->attachments(10))===1,'own file list');
check(count($alice->tasks(10))===1,'own tasks');
expectDenied(fn()=> $alice->tasks(11),'foreign task list');
expectDenied(fn()=> $alice->history(11),'foreign history');
expectDenied(fn()=> $alice->updateLead(11,['status'=>'closing','notes'=>'attack','deal_value'=>'12']),'foreign mutation');
expectDenied(fn()=> $alice->assign([10],3),'member cannot reassign');
expectDenied(fn()=> $alice->members(),'member cannot list accounts');
expectDenied(fn()=> $alice->createMember('evil','evil@example.com','Evil','LongPassword123!'),'member cannot create accounts');
expectDenied(fn()=> $alice->completeTask(10,31),'foreign task completion');
expectDenied(fn()=> $alice->deleteAttachment(21),'foreign file delete');
expectDenied(fn()=> $root->assign([10,999],3),'assignment validates complete batch');
check($alice->lead(10)!==null,'failed assignment atomic');
$alice->updateLead(10,['status'=>'contacted','notes'=>'My note','deal_value'=>'125000']);
check($alice->lead(10)['notes']==='My note','own update works');
check(count($alice->history(10))>0,'actor history recorded');
$alice->addTask(10,'Call next week','2026-11-01T10:00');
check(count($alice->tasks(10))===2,'own task created');
$alice->completeTask(10,30);
check($db->query('SELECT completed_at FROM crm_tasks WHERE id=30')->fetchColumn()!==null,'own task completed');
check($root->assign([10],3)===1,'admin reassigns');
check($alice->lead(10)===null && $bob->lead(10)!==null,'reassignment revokes former owner');
check($alice->attachment(20)===null && $alice->exportRows()===[],'reassignment revokes files and export');
expectDenied(fn()=> $alice->updateLead(10,['status'=>'lost','notes'=>'old owner']),'old owner mutation denied');
expectDenied(fn()=> $root->assign([11],4),'other workspace assignee denied');
expectDenied(fn()=> $root->assign([11],1),'admin not member assignee');
expectDenied(fn()=> $root->disableMember(1),'cannot disable admin');
$id=$root->createMember('new','new@example.com','New member','LongPassword123!');
check($id>4,'admin creates member');
check(password_verify('LongPassword123!',$db->query('SELECT password FROM users WHERE id='.$id)->fetchColumn()),'password hashed');
$root->resetMemberPassword($id,'ChangedPassword123!');
check((int)$db->query('SELECT session_version FROM users WHERE id='.$id)->fetchColumn()===1,'reset revokes sessions');
$root->disableMember(3);
check($db->query('SELECT deleted_at FROM users WHERE id=3')->fetchColumn()!==null,'disabled account blocked');
check($root->lead(10)['assigned_user_id']===null,'disabled member work returned to admin queue');
expectDenied(fn()=> $root->assign([10],3),'disabled assignee rejected');
$db->exec('UPDATE project_leads SET in_crm=0 WHERE id=12');
$root->assign([12],2);
check((int)$root->lead(12)['in_crm']===1,'assigned scraped leads enroll in admin CRM reports');
$root->resetMemberPassword(2,'RevokedPassword123!');
expectDenied(fn()=> $alice->updateLead(12,['status'=>'lost','notes'=>'stale request']),'password reset revokes in-flight mutation');
echo "PASS: $checks checks\n";
