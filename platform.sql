-- Central account registry only. Client business data lives in separate databases.
CREATE TABLE IF NOT EXISTS platform_workspaces (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 state VARCHAR(32) NOT NULL DEFAULT 'pending',
 db_name VARCHAR(64) NULL, db_user VARCHAR(64) NULL, db_secret TEXT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS platform_accounts (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 workspace_id BIGINT UNSIGNED NULL, local_user_id INT UNSIGNED NULL,
 email VARCHAR(100) NOT NULL UNIQUE, username VARCHAR(50) NOT NULL UNIQUE,
 name VARCHAR(100) NOT NULL, phone VARCHAR(30) NOT NULL DEFAULT '',
 state VARCHAR(32) NOT NULL DEFAULT 'pending', password_hash VARCHAR(255) NULL,
 verified_channel VARCHAR(20) NULL, is_platform_admin TINYINT NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY account_workspace(workspace_id,local_user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS platform_tokens (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 token_hash CHAR(64) NOT NULL UNIQUE, purpose VARCHAR(20) NOT NULL,
 account_id BIGINT UNSIGNED NULL, workspace_id BIGINT UNSIGNED NULL,
 email VARCHAR(100) NOT NULL, phone VARCHAR(30) NOT NULL DEFAULT '', channel VARCHAR(20) NOT NULL,
 payload LONGTEXT NULL, expires_at BIGINT NOT NULL, consumed_at BIGINT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY token_account(account_id,purpose), KEY token_expiry(expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS platform_settings (id INT NOT NULL PRIMARY KEY,payload LONGTEXT NOT NULL)
 ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS platform_notification_log (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, account_id BIGINT UNSIGNED NULL,
 purpose VARCHAR(32) NOT NULL, channel VARCHAR(20) NOT NULL, destination_masked VARCHAR(128) NOT NULL,
 status VARCHAR(20) NOT NULL,http_code INT NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS platform_callbacks (
 workspace_id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
 secret_hash CHAR(64) NOT NULL UNIQUE,secret_encrypted TEXT NOT NULL,
 device VARCHAR(100) NOT NULL,updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
