<?php
require __DIR__.'/bootstrap.php';
use App\Models\InboxRepository;
use App\Models\ConversationRepository;
use App\Services\StarsenderWebhook;
date_default_timezone_set('Asia/Jakarta');
$db=fixture();$db->exec('PRAGMA foreign_keys=ON');
$db->exec("ALTER TABLE projects ADD COLUMN total_leads INTEGER DEFAULT 0;
CREATE TABLE crm_lead_sources(lead_id INTEGER PRIMARY KEY,source TEXT);
CREATE TABLE whatsapp_deliveries(id INTEGER PRIMARY KEY,lead_id INTEGER,recipient TEXT,message TEXT,status TEXT,created_at TEXT);
UPDATE project_leads SET phone='081234567890' WHERE id=10;
INSERT INTO whatsapp_deliveries VALUES(1,10,'6281234567890','Known CRM reply','accepted','2026-10-30 17:05:00'),(2,11,'6281234567890','Other owner secret','accepted','2026-10-30 17:06:00'),(3,10,'629999999999','Wrong recipient','accepted','2026-10-30 17:06:00');");
InboxRepository::install($db);$inbox=new InboxRepository($db);$repo=new ConversationRepository($db);
$admin=['id'=>1,'role'=>'admin','workspace_id'=>1];$alice=['id'=>2,'role'=>'user','workspace_id'=>1];$bob=['id'=>3,'role'=>'user','workspace_id'=>1];
$base=['device_id'=>'123','message_id'=>'one','from'=>'081234567890','message'=>'Incoming first','is_me'=>false,'is_group'=>false,'chat_type'=>'personal','timestamp'=>1793354400];
$event=StarsenderWebhook::normalize($base,'123');$event['sent_at']='2026-10-30 10:00:00';$inbox->ingest($event);
$event['message_id']='two';$event['message']='Incoming second';$event['sent_at']='2026-10-30 10:10:00';$inbox->ingest($event);
$groups=$repo->groups($alice,'all',1,'');
check(count($groups)===1,'multiple messages appear as one conversation');
check((int)$groups[0]['message_count']===3,'known CRM reply merged into contact group');
check((int)$groups[0]['unread_count']===2,'conversation review badge counts incoming only');
check($repo->groups($bob,'all',1,'')===[],'other member cannot see conversation');
$thread=$repo->thread($alice,null,10,1);
check(array_column($thread['events'],'message')===['Incoming first','Known CRM reply','Incoming second'],'chronological timeline normalizes local CRM time to UTC');
check(!in_array('Wrong recipient',array_column($thread['events'],'message'),true),'CRM recipient must match prospect phone');
check($repo->thread($bob,null,10,1)===null,'direct lead route is scoped');
$unknown=$event;$unknown['lead_id']=null;$unknown['contact_phone']='6289999999999';$unknown['message_id']='unknown';$unknown['push_name']='New contact';$inbox->ingest($unknown);
$unknownId=(int)$db->query("SELECT id FROM whatsapp_inbox WHERE message_id='unknown'")->fetchColumn();
check(count($repo->groups($admin,'unmatched',1,''))===1,'unmatched contact admin queue');
check($repo->thread($alice,$unknownId,null,1)===null,'unmatched anchor not exposed to members');
$out=$event;$out['contact_phone']=null;$out['direction']='outgoing';$out['message_id']='orphan-out';$out['message']='Cannot guess recipient';$inbox->ingest($out);
check(count($repo->groups($admin,'unknown',1,''))===1,'orphan outgoing separate queue');
check($repo->groups($alice,'unknown',1,'')===[],'members cannot read unknown outgoing');
check(count($repo->groups($admin,'all',1,''))===2,'unknown outgoing excluded from contact list');
check(count($repo->groups($admin,'all',1,'New contact'))===1,'search finds latest contact name');
expectDenied(fn()=>$inbox->createProspect($alice,$unknownId,1,'New business',null),'members cannot create');
expectDenied(fn()=>$inbox->createProspect($admin,$unknownId,2,'New business',null),'cannot select foreign project');
expectDenied(fn()=>$inbox->createProspect($admin,$unknownId,1,'New business',4),'cannot assign foreign member');
$lead=$inbox->createProspect($admin,$unknownId,1,'New business',2);
check($lead>13,'prospect created from verified sender');
$r=$db->query('SELECT * FROM project_leads WHERE id='.$lead)->fetch();
check($r['phone']==='6289999999999' && (int)$r['in_crm']===1 && (int)$r['assigned_user_id']===2,'new prospect enters CRM and member assignment');
check((int)$db->query('SELECT lead_id FROM whatsapp_inbox WHERE id='.$unknownId)->fetchColumn()===$lead,'message linked atomically');
check($inbox->createProspect($admin,$unknownId,1,'Repeat request',2)===$lead,'double submit returns same prospect');
check((int)$db->query('SELECT COUNT(*) FROM project_leads')->fetchColumn()===5,'double submit does not add duplicate');
check(count($repo->groups($alice,'all',1,''))===2,'assigned member sees new conversation');
$follow=$unknown;$follow['message_id']='reply-after-create';$inbox->ingest($follow);
check((int)$db->query("SELECT lead_id FROM whatsapp_inbox WHERE message_id='reply-after-create'")->fetchColumn()===$lead,'future replies follow new prospect');
$db->exec('UPDATE project_leads SET assigned_user_id=3 WHERE id='.$lead);
check($repo->thread($alice,null,$lead,1)===null,'reassignment revokes full thread');
check($repo->thread($bob,null,$lead,1)!==null,'new assignee sees linked thread');
$db->exec('UPDATE project_leads SET in_crm=0 WHERE id=10');
$notCrm=$repo->thread($admin,null,10,1);
check($notCrm['context']['anchor']!==null,'matched non-CRM lead retains incoming anchor for promotion');
$inbox->link($admin,$notCrm['context']['anchor'],10);
check((int)$db->query('SELECT in_crm FROM project_leads WHERE id=10')->fetchColumn()===1,'matched prospect can be promoted into CRM');
echo "Conversations: $checks checks passed\n";
