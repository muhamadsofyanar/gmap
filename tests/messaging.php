<?php
require __DIR__.'/bootstrap.php';
require __DIR__.'/../config/database.php';
use App\Core\Database;use App\Models\BroadcastModel;use App\Models\GatewayModel;use App\Services\MessageDraft;
$db=fixture();(new ReflectionProperty(Database::class,'instance'))->setValue(null,$db);
$db->exec("CREATE TABLE crm_contact_blocks(contact_key TEXT,reason TEXT);
CREATE TABLE whatsapp_broadcasts(token TEXT PRIMARY KEY,project_id INTEGER,template_id INTEGER,template_name TEXT,recipients TEXT,total INTEGER,invalid_count INTEGER,duplicate_count INTEGER,mark_contacted INTEGER);
CREATE TABLE whatsapp_deliveries(id INTEGER PRIMARY KEY,request_token TEXT UNIQUE,lead_id INTEGER,template_id INTEGER,recipient TEXT,message TEXT,status TEXT,http_code INTEGER,updated_at TEXT);
UPDATE project_leads SET phone='081234567890' WHERE id=10;
UPDATE project_leads SET phone='081234567891' WHERE id=11;
UPDATE project_leads SET phone='081234567890' WHERE id=12;");
check(MessageDraft::text('  Pesan bebas diubah  ')==='Pesan bebas diubah','manual body accepted without template');
expectDenied(fn()=>MessageDraft::text(' '),'empty text rejected');
expectDenied(fn()=>MessageDraft::text(str_repeat('a',4001)),'oversized text rejected');
$gateway=(new ReflectionClass(GatewayModel::class))->newInstanceWithoutConstructor();
$r=$gateway->reserve(str_repeat('a',32),10,0,'6281234567890','Custom message');
check($r['created'],'manual message reserved without template');
check(!$gateway->reserve(str_repeat('a',32),10,0,'6281234567890','Custom message')['created'],'same request never sends twice');
expectDenied(fn()=>$gateway->reserve(str_repeat('a',32),10,0,'6281234567890','Changed message'),'changed token message rejected');
expectDenied(fn()=>$gateway->reserve(str_repeat('a',32),10,0,'6281234567891','Custom message'),'changed token recipient rejected');
$broadcast=(new ReflectionClass(BroadcastModel::class))->newInstanceWithoutConstructor();
$template=['id'=>0,'name'=>'Pesan bebas','body'=>'Halo {{nama_bisnis}}'];
expectDenied(fn()=>$broadcast->prepare(str_repeat('b',32),1,$template,false,[]),'empty explicit selection rejected');
expectDenied(fn()=>$broadcast->prepare(str_repeat('b',32),1,$template,false,[13]),'foreign project selection rejected');
$batch=$broadcast->prepare(str_repeat('b',32),1,$template,false,[11]);
check(array_column($batch['recipients'],'id')===[11],'only selected recipient is prepared');
check($batch['recipients'][0]['message']==='Halo Bob lead','personalized draft snapshot');
expectDenied(fn()=>$broadcast->prepare(str_repeat('b',32),1,$template,false,[10]),'changed selection cannot reuse batch token');
expectDenied(fn()=>$broadcast->prepare(str_repeat('b',32),1,['id'=>0,'name'=>'Pesan bebas','body'=>'Changed'],false,[11]),'changed broadcast body cannot reuse token');
expectDenied(fn()=>$broadcast->prepare(str_repeat('b',32),1,['id'=>0,'name'=>'Pesan bebas','body'=>'Halo Bob lead'],false,[11]),'raw draft changes cannot reuse token even when rendering matches');
$dupes=$broadcast->prepare(str_repeat('c',32),1,$template,false,[10,12]);
check(count($dupes['recipients'])===1 && (int)$dupes['duplicate_count']===1,'selected duplicate phone receives one message');
$db->exec("INSERT INTO project_leads(id,project_id,workspace_id,shop_name,phone,in_crm) VALUES(14,1,1,'Another duplicate','081234567890',1)");
expectDenied(fn()=>$broadcast->prepare(str_repeat('c',32),1,$template,false,[10,14]),'different duplicate ID selections cannot reuse token');
$db->exec("INSERT INTO crm_contact_blocks VALUES('phone:6281234567891','stop')");
$blocked=$broadcast->prepare(str_repeat('d',32),1,$template,false,[11]);
check($blocked['recipients']===[],'blocked selected contact excluded');
check(count($broadcast->candidates(1))===4,'candidate list restricted to project CRM');
echo "Messaging: $checks checks passed\n";
